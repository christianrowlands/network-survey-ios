import SwiftUI

/// The project's web pages linked from About.
enum AboutLinks {
    static let website = URL(string: "https://networksurvey.app")!
    /// The same privacy policy page the Network Survey Android app links to.
    static let privacyPolicy = URL(string: "https://networksurvey.app/privacy-policy")!
}

struct AboutView: View {
    var body: some View {
        List {
            Group {
                Section {
                    VStack(alignment: .leading, spacing: Theme.Spacing.s) {
                        Text("Network Survey")
                            .font(Theme.Fonts.screenTitle)
                            .foregroundStyle(Theme.Colors.ink)
                        Text("Version \(Bundle.main.shortVersion) (\(Bundle.main.buildNumber))")
                            .font(Theme.Fonts.body)
                            .foregroundStyle(Theme.Colors.ink2)
                    }
                    .padding(.vertical, Theme.Spacing.xs)
                    Text("Surveys Wi-Fi and Bluetooth with a Network Survey sensor board. The board only listens: it never transmits Wi-Fi frames.")
                        .font(Theme.Fonts.body)
                        .foregroundStyle(Theme.Colors.ink2)
                }
                Section {
                    Link(destination: AboutLinks.website) {
                        Label("networksurvey.app", systemImage: "safari")
                    }
                    Link(destination: AboutLinks.privacyPolicy) {
                        Label("Privacy policy", systemImage: "hand.raised")
                    }
                    .accessibilityIdentifier("about.privacyPolicy")
                    NavigationLink { LicensesView() } label: {
                        Label("Open-source licenses", systemImage: "doc.plaintext")
                    }
                } footer: {
                    Text("Network Survey is open source under the Apache License 2.0. No analytics or tracking.")
                }
            }
            .panelRows()
        }
        .themedList()
        .navigationTitle("About")
        .navigationBarTitleDisplayMode(.inline)
    }
}

/// One bundled third-party component, from third-party-licenses.json
/// (generated by scripts/gen-licenses.sh).
nonisolated struct ThirdPartyLicense: Decodable, Identifiable, Sendable {
    var name: String
    var version: String
    var license: String
    var url: String?
    /// The full license text followed by any NOTICE files.
    var text: String
    /// True for this app's own license and NOTICE.
    var app: Bool?
    var id: String { name }

    static func bundled() -> [ThirdPartyLicense] {
        guard let url = Bundle.main.url(forResource: "third-party-licenses", withExtension: "json"),
              let data = try? Data(contentsOf: url) else { return [] }
        return (try? JSONDecoder().decode([ThirdPartyLicense].self, from: data)) ?? []
    }
}

/// The libraries and data the app ships, each with its full license text.
struct LicensesView: View {
    @State private var licenses = ThirdPartyLicense.bundled()

    var body: some View {
        List {
            Group {
                Section("This app") {
                    ForEach(licenses.filter { $0.app == true }) { row($0) }
                }
                Section {
                    ForEach(licenses.filter { $0.app != true }) { row($0) }
                } header: {
                    Text("Included components")
                } footer: {
                    Text("Network Survey is licensed under the Apache License 2.0. It includes the components above under their own licenses.")
                }
            }
            .panelRows()
        }
        .themedList()
        .navigationTitle("Open-source licenses")
        .navigationBarTitleDisplayMode(.inline)
    }
}

extension LicensesView {
    private func row(_ license: ThirdPartyLicense) -> some View {
        NavigationLink {
            LicenseTextView(license: license)
        } label: {
            VStack(alignment: .leading, spacing: Theme.Spacing.xxs) {
                HStack {
                    Text(license.name).foregroundStyle(Theme.Colors.ink)
                    Spacer()
                    Text(license.license)
                        .font(Theme.Fonts.label)
                        .foregroundStyle(Theme.Colors.ink2)
                }
                Text(license.version)
                    .font(Theme.Fonts.caption.monospacedDigit())
                    .foregroundStyle(Theme.Colors.ink2)
            }
        }
    }
}

private struct LicenseTextView: View {
    let license: ThirdPartyLicense

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: Theme.Spacing.m) {
                if let link = license.url.flatMap(URL.init(string:)) {
                    Link(destination: link) {
                        Label("Project page", systemImage: "safari")
                    }
                }
                Text(license.text)
                    .font(.system(.footnote, design: .monospaced))
                    .foregroundStyle(Theme.Colors.ink)
                    .textSelection(.enabled)
            }
            .padding(Theme.Spacing.screenGutter)
            .frame(maxWidth: .infinity, alignment: .leading)
        }
        .screenBackground()
        .navigationTitle(license.name)
        .navigationBarTitleDisplayMode(.inline)
    }
}

extension Bundle {
    var buildNumber: String {
        object(forInfoDictionaryKey: "CFBundleVersion") as? String ?? "?"
    }
}
